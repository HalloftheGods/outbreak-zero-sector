// Biome ground tiles: flood water, packed snow, ash and toxic sludge. Same recipe as
// grass and dirt in tiles.ts: a flat base, a few stamped marks well clear of the tile
// edge (so neighbours seam without outlines), all of it mid-dark and low contrast so
// figures and zombies still read on top.

