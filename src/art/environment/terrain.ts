export interface TerrainTiles {
  water: PixelCanvas[];
  snow: PixelCanvas[];
  ash: PixelCanvas[];
  sludge: PixelCanvas[];
}

export function buildTerrain(): TerrainTiles {
  return {
    water: WATER.map((rows) => tile(WATER_BASE, rows, WATER_LEGEND)),
    snow: SNOW.map((rows) => tile(SNOW_BASE, rows, SNOW_LEGEND)),
    ash: ASH.map((rows) => tile(ASH_BASE, rows, ASH_LEGEND)),
    sludge: SLUDGE.map((rows) => tile(SLUDGE_BASE, rows, SLUDGE_LEGEND)),
  };
}
